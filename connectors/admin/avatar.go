// El logo de un comercio nuevo, como hace Google sin foto: un círculo de color con la primera letra del nombre
// (decisión de Miguel, 2026-11-19), para que un comercio de prueba no se confunda con otro por un logo copiado.
// El color sale del nombre (siempre el mismo para el mismo nombre). El admin sólo acepta png, jpg o bmp, y el
// módulo no trae fuentes: la letra se dibuja con una tipografía de mapa de bits de 5×7 escalada.

const avatarSize = 256

var avatarPalette = []color.RGBA{
	{0x1A, 0x73, 0xE8, 0xFF}, {0xD9, 0x30, 0x25, 0xFF}, {0x18, 0x80, 0x38, 0xFF}, {0xE3, 0x74, 0x00, 0xFF},
	{0x93, 0x34, 0xE6, 0xFF}, {0x00, 0x7B, 0x83, 0xFF}, {0xC5, 0x22, 0x1F, 0xFF}, {0x39, 0x49, 0xAB, 0xFF},
}

