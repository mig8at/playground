// avatarLetter: la primera letra o dígito del nombre, sin el prefijo de la automatización y sin tildes.
func avatarLetter(name string) rune {
	clean := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(name), AutoPrefix))
	for _, r := range strings.ToUpper(clean) {
		switch r {
		case 'Á':
			r = 'A'
		case 'É':
			r = 'E'
		case 'Í':
			r = 'I'
		case 'Ó':
			r = 'O'
		case 'Ú', 'Ü':
			r = 'U'
		case 'Ñ':
			r = 'N'
		}
		if _, ok := glyphs[r]; ok && (unicode.IsLetter(r) || unicode.IsDigit(r)) {
			return r
		}
	}
	return '?'
}

func avatarColor(name string) color.RGBA {
	h := fnv.New32a()
	_, _ = h.Write([]byte(strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(name), AutoPrefix))))
	return avatarPalette[int(h.Sum32()%uint32(len(avatarPalette)))]
}

// LetterAvatar devuelve el PNG del logo del comercio: 256×256, círculo de color y la letra en blanco.
func LetterAvatar(name string) []byte {
	img := image.NewRGBA(image.Rect(0, 0, avatarSize, avatarSize))
	bg := avatarColor(name)
	c := float64(avatarSize) / 2
	for y := 0; y < avatarSize; y++ {
		for x := 0; x < avatarSize; x++ {
			dx, dy := float64(x)+0.5-c, float64(y)+0.5-c
			if dx*dx+dy*dy <= c*c {
				img.SetRGBA(x, y, bg)
			}
		}
	}
	const scale = 16 // la letra queda de 80×112 px
	g := glyphs[avatarLetter(name)]
	x0, y0 := (avatarSize-5*scale)/2, (avatarSize-7*scale)/2
	white := color.RGBA{0xFF, 0xFF, 0xFF, 0xFF}
	for row := 0; row < 7; row++ {
		for col := 0; col < 5; col++ {
			if g[row]&(1<<(4-col)) == 0 {
				continue
			}
			for y := 0; y < scale; y++ {
				for x := 0; x < scale; x++ {
					img.SetRGBA(x0+col*scale+x, y0+row*scale+y, white)
				}
			}
		}
	}
	var buf bytes.Buffer
	_ = png.Encode(&buf, img)
	return buf.Bytes()
}
